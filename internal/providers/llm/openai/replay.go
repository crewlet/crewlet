// What an assistant turn carries back to the endpoint that wrote it.
//
// The OpenAI Chat Completions schema has no field for a model's reasoning, and
// the hosts that serve reasoning models over it each added their own — and
// then, one by one, documented that the next request must carry it back:
//
//   - Moonshot (kimi-k3, kimi-k2.7-code) and Together's K3: `reasoning_content`
//     on every earlier assistant message, "required in multi-turn
//     conversations and tool-call loops" for K3, which was trained in that
//     mode and cannot have it turned off.
//   - DeepSeek: `reasoning_content` of every earlier turn on a request that
//     carries tools — "the API will return a 400 error" without it — and
//     ignored on one that does not. (The rule this backend used to follow,
//     that a host emitting reasoning_content refuses it on input, was the
//     advice DeepSeek gave for its first reasoner, which other hosts repeated;
//     its documentation says the opposite now.)
//   - Fireworks, Z.ai and SGLang: `reasoning_content`, which interleaved
//     thinking "MUST" see again; MiniMax the same, or `reasoning_details`
//     when asked to split its thinking out.
//   - OpenRouter: `reasoning` beside `reasoning_details`, an array of typed
//     blocks — readable text with a signature, a summary, or an encrypted
//     payload — whose "sequence ... must match the outputs generated by the
//     model during the original request". Groq, vLLM, Ollama and Together's
//     other models answer `reasoning` and accept it back.
//   - A LiteLLM proxy fronting Claude: `thinking_blocks`, signed, "Required!"
//     beside a tool call or the vendor answers 400.
//   - Gemini 3 behind Google's OpenAI-compatible endpoint: a thought signature
//     on the tool calls it signs (`extra_content.google.thought_signature`, on
//     the first of parallel calls; LiteLLM carries it as the call's
//     `provider_specific_fields`), returned "exactly as it was returned by the
//     model" or the step is a 400.
//   - Mistral's reasoning models: no field at all — `content` itself is a list
//     of typed chunks with the thinking in its own chunk, and "always replay
//     the full assistant message (including ThinkChunk)". Read as the string
//     OpenAI's schema promises, that list arrived as its own JSON text, and an
//     answer read that way is the model's thinking printed as JSON.
//
// So every response's reasoning state is kept EXACTLY AS THE HOST SENT IT —
// each of those fields verbatim, the content when it came as a list, and each
// tool call's own fields keyed by its id — as the one element of
// [llm.Message.Raw], and handed back on every later request of the
// conversation in the field and the shape it arrived in. The neutral view
// (Content, ReasoningContent, ToolCalls) is read from the same response and
// is still what the engine reads, and still what the message is built from;
// the record only adds what the neutral view cannot hold. A field the host
// sent EMPTY is kept as it came: a round that reasoned nothing still answered
// `"reasoning_content": ""`, and the host that requires the field checks that
// it is there. Only a null is absence — how a host that prints every field
// says it has nothing in one — and a response that carried nothing else keeps
// no record, so its turn goes back exactly as it always did.
//
// AND ONCE A HOST HAS SHOWN IT SPEAKS reasoning_content, every assistant turn
// of the request carries one ([speaksReasoningContent]). Moonshot refuses a
// tool-call turn without it while thinking is on, and DeepSeek wants every
// earlier turn's; but a stream that reasoned nothing can name the field in no
// fragment, and a turn another endpoint or backend wrote has none this host
// can read. Each goes back with the empty string, the host's own word for no
// reasoning — never another backend's reading of its own turn.
//
// ONLY TO THE ENDPOINT THAT WROTE IT. "OpenAI-compatible" is one wire format
// over many hosts, and a field one host emits is a field another may refuse:
// OpenAI's own endpoint returns none of these and documents none of them as an
// input, and a 400 there is fatal and not retried by the chain. A turn's
// record is therefore BOUND to its endpoint ([llm.Message.Binding], a digest
// of the base URL — [endpointBinding]) and replayed only into a request to the
// same one. Whatever its MODEL: a host decides which model reads which
// reasoning, and both OpenRouter and Google document carrying one model's
// reasoning into a conversation that has moved to another. A turn another
// endpoint wrote is rebuilt from the neutral view without its reasoning, as a
// turn another backend wrote always was (with the empty reasoning_content of
// the paragraph above, where the host speaks it, and the thought signature
// Google documents for a call it did not generate, where the host holds every
// step to one — foreign.go).
//
// THE SCOPE IS THE CONVERSATION, and a conversation here is one phase's tool
// loop: nothing in this engine replays an assistant turn into a later turn's
// request (a turn starts from a structured ledger, never a transcript), so
// every reasoning field sent back belongs to the task the request is still
// working on — which is exactly the scope every host above asks for, and the
// one where DeepSeek's "with tools" and Fireworks' "within the current turn"
// both hold. A suspended run carries the record through its parked row
// (internal/agent/execstate) with the rest of the message, so the rounds
// before a suspension go back as they came.
//
// A STREAM SENDS EACH OF THEM IN FRAGMENTS, and the SDK's accumulator keeps
// none of them, so [streamTurn] builds the same record a whole response would
// have carried: a text field is its fragments concatenated — the empty string
// when its fragments carried no text, because the field was still named; a
// list of blocks (OpenRouter's details, LiteLLM's thinking blocks, Mistral's
// chunks) grows a block while its fragments continue it — same type, same
// index, no signature yet — and starts a new one otherwise, and an empty
// string in a content that has become a list adds no chunk. OpenRouter's own
// SDK joins consecutive fragments of one type the same way and lets a late
// signature land on the block it closes; the index and the signature are what
// keep two blocks of one type, which a whole response lists apart, apart here
// too. A tool call's own fields are taken from the first fragment of that call
// that carries them, filed at the position the SDK's accumulator assembles the
// call at — which a stream that does not number its calls is given first
// ([streamTurn.number]).

// messageFields are the reasoning fields an assistant message carries beside
// OpenAI's schema, and how a stream sends each one.
var messageFields = []struct {
	key    string
	blocks bool // a list of typed blocks; otherwise a string sent in fragments
}{
	{key: "reasoning_content"},
	{key: "reasoning"},
	{key: "reasoning_details", blocks: true},
	{key: "thinking_blocks", blocks: true},
}

// callFields are the fields a tool call carries beside OpenAI's schema that
// hold the model's reasoning state for that call.
var callFields = []string{"extra_content", "provider_specific_fields"}

// growing are the keys a block's fragments CONTINUE rather than replace: the
// text OpenRouter's `reasoning.text` and `reasoning.summary` blocks, LiteLLM's
// thinking blocks and Mistral's text and thinking chunks are written in.
var growing = []string{"text", "summary", "thinking"}

// endpointBinding is the identity a turn's record is bound to: the endpoint's
// base URL, as a digest.
//
// A DIGEST because the URL is the operator's to write and may carry a
// credential — a gateway's password in its userinfo, a key in its query — and
// the binding travels in every parked conversation. The userinfo is dropped
// before hashing for the same reason it is irrelevant: two entries reaching
// one gateway with different passwords reach one host. The scheme and host are
// case-folded and a trailing slash dropped, because `https://API.example/v1/`
// and `https://api.example/v1` are one endpoint, and a binding that told them
// apart would shed reasoning a host still expects.
func endpointBinding(baseURL string) string {
	canonical := strings.TrimSpace(baseURL)
	if u, err := url.Parse(canonical); err == nil && u.Host != "" {
		u.User = nil
		u.Scheme = strings.ToLower(u.Scheme)
		u.Host = strings.ToLower(u.Host)
		u.Path = strings.TrimRight(u.Path, "/")
		u.RawPath = ""
		u.Fragment = ""
		canonical = u.String()
	}
	sum := sha256.Sum256([]byte(canonical))
	return hex.EncodeToString(sum[:])
}

// kept is what a response's assistant message carried beyond the SDK's typed
// message: the record a later request replays, and the neutral readings the
// typed message gets wrong or cannot make.
type kept struct {
	// record is [llm.Message.Raw]'s one element, nil when the message
	// carried nothing the neutral view does not hold.
	record json.RawMessage

	// listed reports content sent as a list of typed chunks, and text is
	// that list's visible text — what Content is, where the typed message
	// holds the list's own JSON.
	listed bool
	text   string

	// reasoning is the readable trace: a reasoning string field, or the
	// thinking chunks of a listed content.
	reasoning string
}

// keptFromMessage reads what a whole assistant message carried beyond the typed
// message, off its raw JSON. A message that is not a JSON object — which the
// SDK decoded anyway — keeps nothing rather than failing a call over it.
func keptFromMessage(msg sdk.ChatCompletionMessage) (kept, error) {
	var fields map[string]json.RawMessage
	if raw := msg.RawJSON(); raw != "" {
		if json.Unmarshal([]byte(raw), &fields) != nil {
			fields = nil
		}
	}
	rec := map[string]json.RawMessage{}
	for _, f := range messageFields {
		if v, ok := fields[f.key]; ok && sent(v) {
			rec[f.key] = v
		}
	}
	var out kept
	if content := fields["content"]; isArray(content) {
		var chunks []map[string]json.RawMessage
		if json.Unmarshal(content, &chunks) == nil {
			out.listed = true
			out.text, out.reasoning = chunkText(chunks)
			rec["content"] = content
		}
	}
	var calls []map[string]json.RawMessage
	if raw, ok := fields["tool_calls"]; ok && isArray(raw) {
		var all []map[string]json.RawMessage
		if json.Unmarshal(raw, &all) == nil {
			for _, call := range all {
				if typeOf(call) == "custom" {
					continue // not in the neutral view: see [Provider.completion]
				}
				calls = appendCallRecord(calls, stringOf(call["id"]), call)
			}
		}
	}
	if readable := reasoningText(msg.RawJSON()); readable != "" {
		out.reasoning = readable
	}
	var err error
	out.record, err = encodeRecord(rec, calls)
	return out, err
}

// appendCallRecord adds a tool call's own fields to calls, keyed by its id, when
// it carries any. A call without an id has nothing to be matched by on the way
// back — and nothing a tool result could answer either.
func appendCallRecord(calls []map[string]json.RawMessage, id string, call map[string]json.RawMessage) []map[string]json.RawMessage {
	if id == "" {
		return calls
	}
	entry := map[string]json.RawMessage{}
	for _, key := range callFields {
		if v, ok := call[key]; ok && sent(v) {
			entry[key] = v
		}
	}
	if len(entry) == 0 {
		return calls
	}
	entry["id"], _ = json.Marshal(id)
	return append(calls, entry)
}

// encodeRecord is the record as one assistant-message-shaped object, or nil
// when there is nothing in it.
func encodeRecord(rec map[string]json.RawMessage, calls []map[string]json.RawMessage) (json.RawMessage, error) {
	if len(calls) > 0 {
		encoded, err := json.Marshal(calls)
		if err != nil {
			return nil, fmt.Errorf("openai: keeping the tool calls' own fields: %w", err)
		}
		rec["tool_calls"] = encoded
	}
	if len(rec) == 0 {
		return nil, nil
	}
	encoded, err := json.Marshal(rec)
	if err != nil {
		return nil, fmt.Errorf("openai: keeping the response's reasoning: %w", err)
	}
	return encoded, nil
}

// streamTurn accumulates, chunk by chunk, what [keptFromMessage] reads off a
// whole message — see the file comment for the merge rules.
type streamTurn struct {
	// texts and blocks hold each reasoning field a fragment named with a
	// value: a field is in its map from the first such fragment, even one
	// that carried no text or no block, because the field's PRESENCE is
	// what a host checks ("reasoning_content is missing").
	texts  map[string]*strings.Builder
	blocks map[string][]*block

	// plain is the content sent as strings, and chunks the content once any
	// fragment of it arrived as a list; plain is folded into chunks then, as
	// the text it was.
	plain  strings.Builder
	chunks []*block
	listed bool

	// calls is each tool call's own fields, by the position the SDK's
	// accumulator assembles the call at ([streamTurn.number]).
	calls map[int64]map[string]json.RawMessage

	// ids is the id each position was opened under, last the position the
	// latest fragment was filed at (once opened is set), and next the
	// position after the highest one yet: what [streamTurn.number] reads
	// an unnumbered fragment against.
	ids    map[int64]string
	last   int64
	next   int64
	opened bool

	// readable is the reasoning text forwarded as it arrived.
	readable strings.Builder
}

// number gives each tool call fragment of d the position of the call it
// belongs to, in place, before the SDK's accumulator reads it.
//
// A host numbers a call's fragments with an `index`, and the accumulator files
// them by it. A host that leaves the index out (Google's OpenAI-compatible
// endpoint has been reported to) or sends -1 (Bedrock's number for a lone
// call) has every fragment filed at 0 there — right for one call, and two
// calls fused into one: their ids overwrite each other and their names and
// arguments run together into a call nothing can run. So an unnumbered
// fragment continues the call last opened when it names no id or that call's
// id, and opens the next position when it names another: the reading a host
// that numbers its calls spells out. A numbered fragment keeps its number.
func (s *streamTurn) number(d *sdk.ChatCompletionChunkChoiceDelta) {
	for i := range d.ToolCalls {
		call := &d.ToolCalls[i]
		if !call.JSON.Index.Valid() || call.Index == -1 {
			if s.opened && (call.ID == "" || call.ID == s.ids[s.last]) {
				call.Index = s.last
			} else {
				call.Index = s.next
			}
		}
		if s.ids == nil {
			s.ids = map[int64]string{}
		}
		if _, named := s.ids[call.Index]; !named && call.ID != "" {
			s.ids[call.Index] = call.ID
		}
		s.last, s.opened = call.Index, true
		if call.Index >= s.next {
			s.next = call.Index + 1
		}
	}
}

// add folds one delta [streamTurn.number] has numbered in, and answers the
// visible text and the reasoning it carried — what the caller forwards. The
// message's own fields are read off the delta's raw JSON, which is the only
// place they are; a delta that is not a JSON object carries none. The tool
// calls are the SDK's typed ones, so each is kept at the position the
// accumulator assembles it at.
func (s *streamTurn) add(d sdk.ChatCompletionChunkChoiceDelta) (content, reasoning string) {
	for _, call := range d.ToolCalls {
		s.addCall(call.Index, call.RawJSON())
	}
	raw := d.RawJSON()
	var delta map[string]json.RawMessage
	if raw == "" || json.Unmarshal([]byte(raw), &delta) != nil {
		return "", ""
	}
	reasoning = reasoningText(raw)
	for _, f := range messageFields {
		v, ok := delta[f.key]
		if !ok || !sent(v) {
			continue
		}
		if f.blocks {
			var pieces []json.RawMessage
			if json.Unmarshal(v, &pieces) != nil {
				continue
			}
			if s.blocks == nil {
				s.blocks = map[string][]*block{}
			}
			if _, named := s.blocks[f.key]; !named {
				// Non-nil, so a field whose fragments held no block
				// is kept as the empty list it was.
				s.blocks[f.key] = []*block{}
			}
			s.blocks[f.key] = mergeBlocks(s.blocks[f.key], pieces)
			continue
		}
		var text string
		if !isString(v) || json.Unmarshal(v, &text) != nil {
			continue
		}
		if s.texts == nil {
			s.texts = map[string]*strings.Builder{}
		}
		b, ok := s.texts[f.key]
		if !ok {
			b = &strings.Builder{}
			s.texts[f.key] = b
		}
		b.WriteString(text)
	}

	switch c := delta["content"]; {
	case isArray(c):
		var pieces []json.RawMessage
		var chunks []map[string]json.RawMessage
		if json.Unmarshal(c, &pieces) == nil {
			if !s.listed {
				s.listed = true
				if s.plain.Len() > 0 {
					s.chunks = mergeBlocks(s.chunks, []json.RawMessage{textChunk(s.plain.String())})
				}
			}
			s.chunks = mergeBlocks(s.chunks, pieces)
			// The forwarded text is read off the delta's own chunks; a
			// chunk that is not an object holds no text this can show.
			_ = json.Unmarshal(c, &chunks)
			text, thought := chunkText(chunks)
			content = text
			reasoning += thought
		}
	case isString(c):
		_ = json.Unmarshal(c, &content)
		switch {
		case !s.listed:
			s.plain.WriteString(content)
		case content != "":
			// An empty string is a fragment that carried something
			// else (a tool call, the finish) and no text: as a chunk
			// it would be one the model never wrote, which a whole
			// response does not hold.
			s.chunks = mergeBlocks(s.chunks, []json.RawMessage{textChunk(content)})
		}
	}

	s.readable.WriteString(reasoning)
	return content, reasoning
}

// addCall keeps a tool call fragment's own fields, the first value each one
// arrives with, under the position the accumulator files the call at.
func (s *streamTurn) addCall(position int64, raw string) {
	var piece map[string]json.RawMessage
	if raw == "" || json.Unmarshal([]byte(raw), &piece) != nil {
		return
	}
	for _, key := range callFields {
		v, ok := piece[key]
		if !ok || !sent(v) {
			continue
		}
		if s.calls == nil {
			s.calls = map[int64]map[string]json.RawMessage{}
		}
		if s.calls[position] == nil {
			s.calls[position] = map[string]json.RawMessage{}
		}
		if _, seen := s.calls[position][key]; !seen {
			s.calls[position][key] = v
		}
	}
}

// kept is the accumulated record and readings, with each call's own fields
// matched to the call the SDK's accumulator assembled at the same position.
func (s *streamTurn) kept(msg sdk.ChatCompletionMessage) (kept, error) {
	rec := map[string]json.RawMessage{}
	for _, f := range messageFields {
		if f.blocks {
			if blocks, named := s.blocks[f.key]; named {
				encoded, err := json.Marshal(blocks)
				if err != nil {
					return kept{}, fmt.Errorf("openai: keeping the streamed %s: %w", f.key, err)
				}
				rec[f.key] = encoded
			}
			continue
		}
		if b, named := s.texts[f.key]; named {
			encoded, err := json.Marshal(b.String())
			if err != nil {
				return kept{}, fmt.Errorf("openai: keeping the streamed %s: %w", f.key, err)
			}
			rec[f.key] = encoded
		}
	}
	out := kept{reasoning: s.readable.String()}
	if s.listed {
		encoded, err := json.Marshal(s.chunks)
		if err != nil {
			return kept{}, fmt.Errorf("openai: keeping the streamed content: %w", err)
		}
		rec["content"] = encoded
		out.listed = true
		var chunks []map[string]json.RawMessage
		_ = json.Unmarshal(encoded, &chunks)
		out.text, _ = chunkText(chunks)
	}
	var calls []map[string]json.RawMessage
	for i, call := range msg.ToolCalls {
		fields := s.calls[int64(i)]
		if fields == nil || call.Type == "custom" {
			continue
		}
		calls = appendCallRecord(calls, call.ID, fields)
	}
	var err error
	out.record, err = encodeRecord(rec, calls)
	return out, err
}

// block is one element of a streamed list of typed blocks, as it grows.
type block struct {
	// whole is an element that is not a JSON object, kept as it came and
	// never continued.
	whole json.RawMessage

	// fields is every key but the growing ones, each at the latest value it
	// arrived with — or the null it arrived as, so a block keeps the keys a
	// whole response would have shown.
	fields map[string]json.RawMessage

	// text and parts are the [growing] keys: text sent as strings, pieces
	// sent as lists of blocks (Mistral's thinking chunk holds its text so).
	// Builders rather than re-encoded values, because a long trace arrives
	// in thousands of fragments and each would copy all the ones before it.
	text  map[string]*strings.Builder
	parts map[string][]*block
}

// mergeBlocks folds streamed pieces onto the blocks so far: a piece CONTINUES
// the last block when it is of the same type, numbers itself as that block (or
// not at all), the last block is not sealed by a signature yet, and one of the
// two carries a [growing] key — and starts a new block otherwise. A continued
// block's growing keys are appended to (a string's text, a list's pieces, by
// the same rule); any other key the piece carries a value for replaces the
// block's, which is how a signature, an id or a format that arrives late
// lands on the block it belongs to.
func mergeBlocks(blocks []*block, pieces []json.RawMessage) []*block {
	for _, raw := range pieces {
		var piece map[string]json.RawMessage
		if firstByte(raw) != '{' || json.Unmarshal(raw, &piece) != nil {
			blocks = append(blocks, &block{whole: raw})
			continue
		}
		if n := len(blocks); n > 0 && blocks[n-1].continuedBy(piece) {
			blocks[n-1].absorb(piece)
			continue
		}
		b := &block{}
		b.absorb(piece)
		blocks = append(blocks, b)
	}
	return blocks
}

// continuedBy reports whether piece is more of b. Either may be the one
// carrying the growing key: a fragment holding nothing but the signature that
// closes a block is still that block's, and OpenRouter's own SDK folds it in
// the same way. A block neither carries one of (an encrypted payload) is whole
// in every fragment, and never continued.
func (b *block) continuedBy(piece map[string]json.RawMessage) bool {
	if b.whole != nil || stringOf(b.fields["type"]) != stringOf(piece["type"]) ||
		stringOf(b.fields["signature"]) != "" {
		return false
	}
	if index, ok := piece["index"]; ok && present(index) &&
		!bytes.Equal(compact(index), compact(b.fields["index"])) {
		return false
	}
	if len(b.text) > 0 || len(b.parts) > 0 {
		return true
	}
	for _, key := range growing {
		if v := piece[key]; isString(v) || isArray(v) {
			return true
		}
	}
	return false
}

// absorb adds a piece's keys to b: a growing key's text or pieces appended,
// any other key's value replacing b's when it holds one.
func (b *block) absorb(piece map[string]json.RawMessage) {
	for k, v := range piece {
		if isGrowing(k) && b.grow(k, v) {
			continue
		}
		if b.fields == nil {
			b.fields = map[string]json.RawMessage{}
		}
		if _, held := b.fields[k]; !held || present(v) {
			b.fields[k] = v
		}
	}
}

// grow appends a growing key's continuation, reporting false for a value that
// is neither text nor a list — which is then kept as an ordinary key.
func (b *block) grow(key string, v json.RawMessage) bool {
	switch {
	case isString(v):
		var text string
		if json.Unmarshal(v, &text) != nil {
			return false
		}
		if b.text == nil {
			b.text = map[string]*strings.Builder{}
		}
		t, ok := b.text[key]
		if !ok {
			t = &strings.Builder{}
			b.text[key] = t
		}
		t.WriteString(text)
		return true
	case isArray(v):
		var pieces []json.RawMessage
		if json.Unmarshal(v, &pieces) != nil {
			return false
		}
		if b.parts == nil {
			b.parts = map[string][]*block{}
		}
		b.parts[key] = mergeBlocks(b.parts[key], pieces)
		return true
	}
	return false
}

// MarshalJSON writes the block as the one object its fragments add up to.
func (b *block) MarshalJSON() ([]byte, error) {
	if b.whole != nil {
		return b.whole, nil
	}
	out := make(map[string]json.RawMessage, len(b.fields)+len(b.text)+len(b.parts))
	for k, v := range b.fields {
		out[k] = v
	}
	for k, t := range b.text {
		encoded, err := json.Marshal(t.String())
		if err != nil {
			return nil, err
		}
		out[k] = encoded
	}
	for k, p := range b.parts {
		encoded, err := json.Marshal(p)
		if err != nil {
			return nil, err
		}
		out[k] = encoded
	}
	return json.Marshal(out)
}

// chunkText reads a content chunk list's visible text and its thinking: the
// text of every `text` chunk, and the text inside every `thinking` chunk (a
// string, or a list of text chunks), each thinking chunk a paragraph.
func chunkText(chunks []map[string]json.RawMessage) (text, thinking string) {
	var visible strings.Builder
	var thoughts []string
	for _, chunk := range chunks {
		switch typeOf(chunk) {
		case "text":
			visible.WriteString(stringOf(chunk["text"]))
		case "thinking":
			inner := chunk["thinking"]
			if isString(inner) {
				thoughts = append(thoughts, stringOf(inner))
				continue
			}
			var parts []map[string]json.RawMessage
			if json.Unmarshal(inner, &parts) == nil {
				var b strings.Builder
				for _, part := range parts {
					if typeOf(part) == "text" {
						b.WriteString(stringOf(part["text"]))
					}
				}
				thoughts = append(thoughts, b.String())
			}
		}
	}
	return visible.String(), strings.Join(thoughts, "\n\n")
}

// textChunk is text sent as a plain string, as the chunk a list holds it in.
func textChunk(text string) json.RawMessage {
	encoded, _ := json.Marshal(map[string]string{"type": "text", "text": text})
	return encoded
}

// replay is a turn's record decoded for the request it goes back in: the
// message's own fields, and each tool call's own fields by the call's id.
type replay struct {
	fields map[string]json.RawMessage
	calls  map[string]map[string]json.RawMessage
}

// replays decodes the record of every turn in messages that goes back to the
// endpoint whose identity is binding, by the turn's position.
func replays(messages []llm.Message, binding string) (map[int]replay, error) {
	out := map[int]replay{}
	for i, m := range messages {
		if !replayable(m, binding) {
			continue
		}
		if len(m.Raw) != 1 {
			return nil, fmt.Errorf("openai: message %d: its kept reasoning has %d parts, want 1", i, len(m.Raw))
		}
		r, err := decodeRecord(m.Raw[0])
		if err != nil {
			return nil, fmt.Errorf("openai: message %d: %w", i, err)
		}
		out[i] = r
	}
	return out, nil
}

// decodeRecord reads a record [encodeRecord] wrote.
func decodeRecord(record json.RawMessage) (replay, error) {
	var fields map[string]json.RawMessage
	if err := json.Unmarshal(record, &fields); err != nil || fields == nil {
		// Only a parked conversation corrupted in storage can hold one, and
		// sent as it is the request would carry nothing of what the host
		// asked to see again.
		return replay{}, errors.New("its kept reasoning is not a JSON object")
	}
	r := replay{fields: fields, calls: map[string]map[string]json.RawMessage{}}
	if raw, ok := fields["tool_calls"]; ok {
		var calls []map[string]json.RawMessage
		if err := json.Unmarshal(raw, &calls); err != nil {
			return replay{}, fmt.Errorf("its tool calls' kept fields are not a list: %w", err)
		}
		for _, call := range calls {
			id := stringOf(call["id"])
			delete(call, "id")
			r.calls[id] = call
		}
		delete(fields, "tool_calls")
	}
	return r, nil
}

// into adds the record to the message built from its turn's neutral view:
// each tool call's own fields onto the call with the same id, and the
// message's own fields — each reasoning field, and a listed content in place
// of the text one — into extra, which the caller sets on the message once it
// holds everything the message carries.
func (r replay) into(msg *sdk.ChatCompletionAssistantMessageParam, extra map[string]any) {
	for k, v := range r.fields {
		extra[k] = v
	}
	if _, listed := r.fields["content"]; listed {
		msg.Content = sdk.ChatCompletionAssistantMessageParamContentUnion{}
	}
	for i := range msg.ToolCalls {
		call := msg.ToolCalls[i].OfFunction
		if call == nil {
			continue
		}
		own, ok := r.calls[call.ID]
		if !ok {
			continue
		}
		fields := make(map[string]any, len(own))
		for k, v := range own {
			fields[k] = v
		}
		call.SetExtraFields(fields)
	}
}

// reasoningContentField is the one reasoning field every assistant message
// carries once its host has shown it speaks it — see [speaksReasoningContent].
const reasoningContentField = "reasoning_content"

// speaksReasoningContent reports whether a turn going back to this endpoint
// carries reasoning_content — which makes every assistant message of the
// request carry one, the empty string where it has none.
//
// The hosts that speak that field refuse a turn without it, not only a turn
// without its reasoning: Moonshot answers an assistant tool-call message with
// no reasoning_content, while thinking is on, "thinking is enabled but
// reasoning_content is missing" (and a client fixed it by sending the empty
// string — charmbracelet/fantasy#196, run against Kimi), and DeepSeek wants
// every earlier turn's "even for turns where the model did not perform a tool
// call", or a 400. A round that reasoned nothing can stream no fragment of the
// field at all, and a turn another endpoint or backend wrote has none this host
// can read; the empty string is the host's own word for "no reasoning", where
// any other value would be a reasoning the host never wrote — another
// backend's reading of its own turn included. The evidence that a host speaks
// the field is in the request itself, a turn it wrote carrying it, because it
// is a fact about the HOST: guessed from a model name, it would put a field
// OpenAI's own endpoint never documented into its requests. No other field is
// filled in: OpenRouter's `reasoning` and `reasoning_details` and the rest
// carry no such rule, and an invented empty block would be a sequence the
// model never produced.
func speaksReasoningContent(records map[int]replay) bool {
	for _, r := range records {
		if _, ok := r.fields[reasoningContentField]; ok {
			return true
		}
	}
	return false
}

// replayable reports whether m is an assistant turn this endpoint wrote with
// reasoning state kept, which goes back with it.
func replayable(m llm.Message, binding string) bool {
	return m.Role == llm.RoleAssistant && m.Origin.Provider == wireName &&
		len(m.Raw) > 0 && m.Binding == binding
}

func isGrowing(key string) bool {
	for _, k := range growing {
		if k == key {
			return true
		}
	}
	return false
}

// present reports a block fragment's value that says something about the
// block: not absent, not null, and not an empty string, list or object. A
// fragment repeats a block's keys with nothing in them (a `"signature": ""`
// before the signature arrives), and one of those must neither replace what
// an earlier fragment set nor number a block apart.
func present(v json.RawMessage) bool {
	switch string(compact(v)) {
	case "", "null", `""`, "[]", "{}":
		return false
	}
	return true
}

// sent reports a field the host sent a value in: anything but absent or JSON
// null, which is how a host that prints every field it has says it has
// nothing in one. An EMPTY value is the host's answer and is kept — Moonshot
// refuses a tool-call turn whose reasoning_content is missing, the round that
// reasoned nothing included — so this is not [present], which judges what a
// fragment adds to a block and where an empty string adds nothing.
func sent(v json.RawMessage) bool {
	switch string(compact(v)) {
	case "", "null":
		return false
	}
	return true
}

func isArray(v json.RawMessage) bool  { return firstByte(v) == '[' }
func isString(v json.RawMessage) bool { return firstByte(v) == '"' }

func firstByte(v json.RawMessage) byte {
	trimmed := bytes.TrimSpace(v)
	if len(trimmed) == 0 {
		return 0
	}
	return trimmed[0]
}

func compact(v json.RawMessage) []byte {
	var b bytes.Buffer
	if json.Compact(&b, v) != nil {
		return bytes.TrimSpace(v)
	}
	return b.Bytes()
}

func typeOf(block map[string]json.RawMessage) string { return stringOf(block["type"]) }

func stringOf(v json.RawMessage) string {
	var s string
	if !isString(v) || json.Unmarshal(v, &s) != nil {
		return ""
	}
	return s
}
