// What a turn an endpoint did NOT write must carry to it.
//
// replay.go sends a turn's reasoning back only to the endpoint that wrote it,
// so a turn another endpoint or backend wrote — the rounds before a fallback
// chain moved the loop — goes back with nothing beside OpenAI's schema. (A
// round an older model wrote on the SAME endpoint goes back with the record it
// kept, whatever the model, and lacks what a rule below checks only where that
// record never held it.) Most hosts take such a turn as it is. Two kinds do
// not, and both refuse it on the FIRST request after a fallback, when the
// endpoint has written nothing a request could show its rules by — so for
// both, the host is known from its URL as well as from what it wrote.
//
// DeepSeek and Moonshot refuse an assistant message without
// reasoning_content: DeepSeek "for requests carrying the tools parameter, the
// reasoning_content must be fully passed back to the API in all subsequent
// requests — even for turns where the model did not perform a tool call ...
// the API will return a 400 error" (its Thinking Mode guide, where thinking
// is on by default), and Moonshot answers a tool-call message without it
// "thinking is enabled but reasoning_content is missing" (Kimi K3 and
// kimi-k2.7-code always think). replay.go gives every assistant message an
// empty one once a turn this endpoint wrote shows it speaks the field
// ([speaksReasoningContent]); their own APIs — api.deepseek.com, and
// Moonshot's api.moonshot.ai and api.moonshot.cn — get it from the first
// request ([reasoningContentHost]). The other hosts that speak the field
// document no refusal of a message without it, or serve other models beside
// the one that does (Together's Kimi K3), and keep the rule of evidence: a
// field a model was never served with is one its host may refuse.
//
// And Gemini 3 holds every function-call step of the current turn to a value
// only its model can write, a thought signature: "omitting a required
// thought_signature for the first functionCall part in any step of the
// current turn results in a 400 error", and on the OpenAI-compatible
// endpoints that signature is the tool call's
// `extra_content.google.thought_signature`, on the first call of a step.
// For "functionCall parts that were not generated by the API and therefore
// don't have an associated thought signature (for example, when transferring
// history from a model that does not include thought signatures)", Google
// gives the one value to send instead — skip_thought_signature_validator, "a
// last resort as it will negatively impact model performance". (All three are
// from the thought-signatures page, "When using REST or manual handling" and
// its Chat Completions examples:
// https://docs.cloud.google.com/gemini-enterprise-agent-platform/models/thinking/thought-signatures
// — the Gemini API's own page now covers only its Interactions API.) Without
// the value, a fallback onto Gemini in the middle of a tool loop was refused
// on its first request, and a 400 is fatal: the chain does not try another
// member.
//
// So a step that goes to Google with no signature on any of its calls carries
// that value on its FIRST call ([signStep]), the call a parallel step's
// signature rides on, beside whatever that call came with; the others carry
// no signature, as the model's own parallel steps do. A step that carries a
// signature is never touched: the stand-in replaces nothing the model wrote.
// A signature ANOTHER endpoint wrote is not this one's to read and replay.go
// never sends it — a step one of Google's endpoints signed goes to the other
// with the stand-in too, which is the case of a chain whose members are
// Vertex AI and the Gemini API.
//
// EVERY UNSIGNED STEP, not only the current turn's. Google's turn begins at
// "the most recent user message that is not a functionResponse", and this
// engine's tool loop puts user messages after tool results — a person's note
// to a running turn, a phase extension's nudge — where how Google's
// translation of an OpenAI conversation draws that line is documented nowhere.
// A step it counts that went without a signature is the 400 this removes; a
// step it does not count is not checked, and the stand-in carries no
// reasoning, as the step without it carried none.
//
// THE LITERAL STRING, never base64. The field is bytes in Google's schema
// (Vertex AI's OpenAI page, "extra_content features") and a real signature
// arrives base64-encoded, but the value Google documents is the string
// itself — which is what the Vercel AI SDK's Google provider sends — and a
// client that sent the base64 of it instead was answered "Thought signature
// is not valid" (langchain-ai/langchain-google#1570).
//
// WHICH HOSTS. Google's own endpoints, known from the URL ([googleEndpoint]);
// and any other endpoint that signed a call of this conversation the same way
// ([signedByGoogle]) — a gateway passing Google's fields through — known from
// what it wrote. Never a host that signs nothing: OpenAI's own endpoint
// documents no `extra_content`, and a field a host does not know is one it may
// refuse. A gateway that carries the signature in a field of its own
// (LiteLLM's `provider_specific_fields`, OpenRouter's `reasoning_details`) is
// sent nothing here: it translates its field into Google's, and what it sends
// for a step it holds no signature for is its own decision — LiteLLM sends
// Google's stand-in.
//
// WHICH MODELS. A Gemini, and not one of the generations before 3: "Gemini 3
// models enforce stricter validation on thought signatures than previous
// Gemini versions", and the stand-in is documented with Gemini 3's rules. An
// id is read by its last path segment (Vertex AI names a model
// google/gemini-…), and one that names no generation (gemini-flash-latest) is
// read as the current one, because the newer a model the stricter its rule. A
// model on Google's endpoints that is not a Gemini — Gemma, or a partner model
// on Vertex AI — is held to none of it.

// skipThoughtSignature is the value Google documents for a function call it
// did not generate.
const skipThoughtSignature = "skip_thought_signature_validator"

// hostOf is the host a base URL names, case-folded, without its port or the
// root's trailing dot (a fully qualified name is the same host); empty for one
// that does not parse.
func hostOf(baseURL string) string {
	u, err := url.Parse(strings.TrimSpace(baseURL))
	if err != nil {
		return ""
	}
	return strings.TrimSuffix(strings.ToLower(u.Hostname()), ".")
}

// reasoningContentHost reports whether baseURL is the API of a host that
// refuses an assistant message without reasoning_content: DeepSeek's, and
// Moonshot's international and mainland ones.
func reasoningContentHost(baseURL string) bool {
	switch hostOf(baseURL) {
	case "api.deepseek.com", "api.moonshot.ai", "api.moonshot.cn":
		return true
	}
	return false
}

// googleHost matches a name of one of the two services that serve Gemini on an
// OpenAI-compatible endpoint — the Gemini API (generativelanguage) and Vertex
// AI (aiplatform) — in each of the grammars Google names a service's endpoints
// by (https://docs.cloud.google.com/docs/security/compliance/endpoints, and
// Private Service Connect's in
// https://docs.cloud.google.com/vpc/docs/configure-private-service-connect-apis):
//
//	SERVICE.googleapis.com                   global
//	LOCATION-SERVICE.googleapis.com          locational: us-central1-aiplatform
//	SERVICE.LOCATION.rep.googleapis.com      regional and multi-regional
//	SERVICE.LOCATION.p.rep.googleapis.com    the same, private
//	SERVICE-ENDPOINT.p.googleapis.com        a Private Service Connect endpoint
//
// THE GRAMMAR, not a list of the hosts in use today. Gemini 3 is served beyond
// the global and locational hosts: Vertex AI's jurisdictional multi-region
// endpoints (aiplatform.us.rep.googleapis.com and
// aiplatform.eu.rep.googleapis.com, on its "Deployments and endpoints" page)
// are "designed exclusively for the Gemini 3 family and future versions", and
// serve Chat Completions (its "Supported capabilities" page); and a deployment
// inside a VPC reaches Vertex AI by the name its Private Service Connect
// endpoint was given (aiplatform-genai1.p.googleapis.com, in Vertex AI's own
// example). A name left out is a fallback refused there on its first request;
// a name a service does not answer to is never reached at all.
var googleHost = regexp.MustCompile(`^(?:` +
	`(?:[a-z0-9-]+-)?(?:generativelanguage|aiplatform)` +
	`|(?:generativelanguage|aiplatform)\.[a-z0-9-]+(?:\.p)?\.rep` +
	`|(?:generativelanguage|aiplatform)-[a-z0-9-]+\.p` +
	`)\.googleapis\.com$`)

// googleEndpoint reports whether baseURL is one of Google's own
// OpenAI-compatible endpoints, by its host ([googleHost]).
func googleEndpoint(baseURL string) bool {
	return googleHost.MatchString(hostOf(baseURL))
}

// olderGemini matches a Gemini model id from before generation 3.
var olderGemini = regexp.MustCompile(`^gemini-[12](?:[.-]|$)`)

// geminiModel reads a model id: whether it names a Gemini, and whether that
// Gemini is one of the generations before 3.
func geminiModel(model string) (gemini, older bool) {
	name := strings.ToLower(strings.TrimSpace(model))
	if i := strings.LastIndex(name, "/"); i >= 0 {
		name = name[i+1:]
	}
	return strings.HasPrefix(name, "gemini-"), olderGemini.MatchString(name)
}

// signsSteps reports whether every function-call step of a request to this
// endpoint goes with a thought signature — the stand-in where it has none.
func (p *Provider) signsSteps(records map[int]replay) bool {
	gemini, older := geminiModel(p.model)
	if older {
		return false
	}
	return (p.google && gemini) || signedByGoogle(records)
}

// signedByGoogle reports whether a turn this endpoint wrote carries a Google
// thought signature on one of its calls.
func signedByGoogle(records map[int]replay) bool {
	for _, r := range records {
		for _, call := range r.calls {
			if thoughtSignature(call["extra_content"]) != "" {
				return true
			}
		}
	}
	return false
}

// thoughtSignature is the signature a call's extra_content carries, and empty
// when it carries none.
func thoughtSignature(extra json.RawMessage) string {
	var content struct {
		Google struct {
			ThoughtSignature string `json:"thought_signature"`
		} `json:"google"`
	}
	if !sent(extra) || json.Unmarshal(extra, &content) != nil {
		return ""
	}
	return content.Google.ThoughtSignature
}

// signStep gives a step whose calls carry no thought signature the stand-in,
// on its first call, beside whatever that call already carries.
func signStep(msg *sdk.ChatCompletionAssistantMessageParam) error {
	var first *sdk.ChatCompletionMessageFunctionToolCallParam
	for i := range msg.ToolCalls {
		call := msg.ToolCalls[i].OfFunction
		if call == nil {
			continue
		}
		if first == nil {
			first = call
		}
		// A call's own fields are the record's, as replay.go set them.
		if own, ok := call.ExtraFields()["extra_content"].(json.RawMessage); ok && thoughtSignature(own) != "" {
			return nil
		}
	}
	if first == nil {
		return nil
	}
	fields := make(map[string]any, len(first.ExtraFields())+1)
	for k, v := range first.ExtraFields() {
		fields[k] = v
	}
	own, _ := fields["extra_content"].(json.RawMessage)
	signed, err := withStandIn(own)
	if err != nil {
		return err
	}
	fields["extra_content"] = signed
	first.SetExtraFields(fields)
	return nil
}

// withStandIn is a call's extra_content with the stand-in as its thought
// signature, keeping every other key it holds. A value that is not an object
// holds nothing Google reads — its schema makes extra_content one — so the
// stand-in takes its place rather than leave the step to the 400.
func withStandIn(extra json.RawMessage) (json.RawMessage, error) {
	content := map[string]json.RawMessage{}
	if sent(extra) && json.Unmarshal(extra, &content) != nil {
		content = map[string]json.RawMessage{}
	}
	google := map[string]json.RawMessage{}
	if g := content["google"]; sent(g) && json.Unmarshal(g, &google) != nil {
		google = map[string]json.RawMessage{}
	}
	// The constant needs no escaping, so its JSON is the string quoted.
	google["thought_signature"] = json.RawMessage(`"` + skipThoughtSignature + `"`)
	var err error
	if content["google"], err = json.Marshal(google); err != nil {
		return nil, fmt.Errorf("openai: signing a step Google did not write: %w", err)
	}
	encoded, err := json.Marshal(content)
	if err != nil {
		return nil, fmt.Errorf("openai: signing a step Google did not write: %w", err)
	}
	return encoded, nil
}
