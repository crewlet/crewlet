-- A revision finds the history row its record wrote.
--
-- A revision records who wrote it as the actor, which for a person writing
-- through their own token is the TOKEN. The person is on the history row the
-- same record wrote (`actor_seat`, migration 0041), and a revision and that
-- row share the record's log position, so a page's revision list joins the two
-- on (page, position) to draw the person rather than the credential.
--
-- Without this index the join reads every history row of the page once per
-- revision listed, and a page keeps a hundred revisions.
CREATE INDEX pages_history_page_version_idx ON pages_history (page_id, version);           -- a revision's history row
