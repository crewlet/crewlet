-- A merge is recorded on its change.
--
-- A change MERGES by a merge record on its repository's own subject (internal/
-- code's merge.go, ADR-0066): one record its committer decides from one
-- snapshot — the change's merge gate met with the record's principal as the
-- merger, or a person's override of it — that marks the change merged, moves
-- its target onto the commit its merge built and lands that move as a push. The
-- change's row keeps who merged it, beside how (merged_via `direct`, a value
-- code.MergedVias gains) and at which commit (merge_oid), which 0058 already
-- holds:
--   - merged_by is who merged it through its gate — a seat by its handle, or a
--     person by the human seat they hold — and merged_by_kind which (agent or
--     person, code.PartyKinds); merged_operator_id is the credential a person
--     merged with, as owner_operator_id is the one they opened it with
--     (iam.ActorFor's attribution), and '' for a seat's.
--   - override_reason is a person's reason for merging the change past its
--     gate, at most code.MaxOverrideReasonBytes (1 KiB), and '' for a merge
--     its gate held.
-- Each is '' on every change no merge record merged: a change a push merged —
-- its target pushed to its head, or past it — names its pusher on that push's
-- row in code_pushes, and nothing here.
--
-- WHERE THE MERGE LANDED IS THE ROW'S OWN position: a merged change is final —
-- no record writes its row again, an edit, a draft's state, a retarget and a
-- close each taking a live change, and a reopen a closed one — so the
-- position of the last record that wrote it is the merge record's, and a
-- column beside it would only ever hold the same number.
--
-- THE ROW STAYS THE WIDTH 0066 SIZED IT TO: the override reason is bounded as
-- the close reason is, and a row holds one or the other, never both — a merged
-- change was never closed since it was last opened, a reopen clearing its
-- close reason. NO INDEX: nothing seeks a change by who merged it, and every
-- write of the columns is a merge's, which rewrites the state's indexes
-- already (TestAChangeWriteRewritesOnlyTheIndexesItMoves).
--
-- A merge's other writes take no column of their own: its push row's `via` is
-- `merge` (code.ViaMerge) and its pack's row's `kind` is `merge` (code.PackMerge),
-- both TEXT columns no CHECK closes, whose closed sets are the code's, and its
-- landing and green rows are 0082's.
--
-- Class: code_changes stays reproducible: written only by the applier, from the
-- records on the repository's subject, and removed only by the repository's
-- purge.
ALTER TABLE code_changes ADD COLUMN merged_by TEXT NOT NULL DEFAULT '';
ALTER TABLE code_changes ADD COLUMN merged_by_kind TEXT NOT NULL DEFAULT '';
ALTER TABLE code_changes ADD COLUMN merged_operator_id TEXT NOT NULL DEFAULT '';
ALTER TABLE code_changes ADD COLUMN override_reason TEXT NOT NULL DEFAULT '';
