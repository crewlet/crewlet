-- A queued check is found by when it falls overdue.
--
-- The code_checks_backlog alarm counts the queued attempts of checks that have
-- waited for a runner longer than their OWN timeout_seconds (ADR-0015: the
-- threshold is every check's, never the alarm's), and it reads at most
-- code.BacklogScan rows a reading. It walked code_checks_queued_idx, oldest
-- QUEUED first — but each attempt is judged at its own timeout, from a second
-- to six hours, so the oldest queued are not the first overdue: a thousand
-- attempts of a fifty-minute check queued a minute before a one-minute lint
-- filled every place of the reading, none of them overdue yet, and the lint,
-- stuck for an hour behind them, was never read. That is the case the alarm is
-- for — a fleet whose runners are gone holding thousands of attempts — and it
-- raised nothing until the oldest attempts passed their own, far longer,
-- timeouts.
--
-- So a queued attempt carries the instant it FALLS OVERDUE: overdue_at, its
-- queued_at plus its definition's timeout_seconds (both in the store's
-- microseconds), written by the applier from the attempt's queue whenever it
-- writes the row — 0 for an attempt with no timeout, which a person's CI
-- reports and no runner of the engine claims, and so is never overdue.
--
-- code_checks_overdue_idx is the queued attempts with a timeout BY THAT
-- INSTANT: the backlog's walk reads the ones overdue by a reading's moment in
-- the order they fell overdue, every row it reads one past its own timeout, so
-- its count is exact up to its bound. PARTIAL on a queued attempt with an
-- instant (state = 'queued' AND overdue_at > 0), so a claimed, an ended or a
-- reported attempt costs it nothing. It carries the key and nothing more: the
-- pinned planner reads each row it seeks for the state its predicate names,
-- so a column carried for the reading would be read twice.
--
-- code_checks_queued_idx stays: it is the attempts oldest queued first, the
-- order a runner claims them in (fairness among the waiting), which the
-- backlog no longer reads.
--
-- THE DEFAULT IS 0 — never overdue — because SQLite requires one for a NOT
-- NULL column added to a table. No release carries the code domain (the
-- domain's stated condition, code.RecordVersion), so no store anywhere holds a
-- row of 0098 outside a development branch, and none is rewritten here.
--
-- Class: code_checks stays reproducible (code.ReproducibleTables): the column
-- is written only by the applier, from the records on a repository's checks
-- subject, and an index carries no rows of its own.
ALTER TABLE code_checks ADD COLUMN overdue_at INTEGER NOT NULL DEFAULT 0;

CREATE INDEX code_checks_overdue_idx ON code_checks (overdue_at, repo_id, commit_oid, name, attempt)
    WHERE state = 'queued' AND overdue_at > 0;    -- the queued attempts by when each falls overdue: the backlog alarm's walk
