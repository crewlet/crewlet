-- A repository digests its path owners.
--
-- code_repos.owners_digest is the digest of the repository's path owners
-- (gitlet.OwnersDigest: the SHA-256, in lowercase hex, of their one canonical
-- JSON form), written by the applier in the same statement batch that writes
-- the code_path_owners rows it digests — a create, a settings change and a
-- restore, every record that writes them.
--
-- A revision's facts record the digest of the owners its home matched its
-- touched paths against (code_revision_facts.owners_digest, 0102), and three
-- readers ask whether that match is still the repository's:
--   - the merge gate, judging owners_approve on every read of a change and
--     every row of a listing and on every round of an enqueue's and a
--     mergeability's decide — which hashed every owner row of the repository,
--     up to a quarter of a mebibyte of them, on each, and now reads one column;
--   - a revise's decide, which refuses facts matched against owners other
--     than its snapshot's;
--   - and the home's due listing, which lists a change whose head revision's
--     facts were matched against owners the repository no longer has as due
--     its facts again: a statement cannot hash, and without the column a
--     change of the owners left every live change's owners_approve computing
--     until something pushed to it, the home never asked to match again.
--
-- THE DEFAULT IS '' — no digest at all — because SQLite requires one for a
-- NOT NULL column added to a table, and every record that writes the owners
-- writes the column: '' is the digest of nothing, so a row an apply forgot
-- would read as owners no facts were matched against, never as a match that
-- holds (0107's reason). No release carries the code domain (its stated
-- condition, gitlet.RecordVersion), so no store outside a development branch
-- holds a repository the column was not written for.
--
-- NO INDEX: every reader reaches the column through the repository's key.
--
-- Class: code_repos stays reproducible: the column is written only from the
-- records the applier applies.
ALTER TABLE code_repos ADD COLUMN owners_digest TEXT NOT NULL DEFAULT '';
