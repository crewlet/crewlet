-- A record of repository reads counts the reads it stands for.
--
-- `code_fetched` was ONE read of a `visibility: unit` repository's contents,
-- published as the read was answered. The node now files each read in a
-- ledger (internal/code/readaudit) and publishes one record a flush for each
-- reader's reads of one repository by one way, counting them in its `reads`
-- field, so the usage day sums that count where it counted rows
-- (store.DB.usageRepoReads) — in a column beside node/0059's six, filled when
-- the row is written, for node/0059's reason: the derivation runs again on
-- every fifteen-second tick its day moves, and reads no JSON.
--
-- WHO HAS TO AGREE ON IT: this node alone, like the rows it describes — the
-- event log is the node's own estate (ADR-0021).
--
-- ZERO ON EVERY OTHER ROW, the default, as node/0059's columns are: a byte a
-- row no reader of another type has to know is there. A `code_fetched` row
-- counting no read is no read, and the derivation leaves it out. NOTHING IS
-- BACKFILLED: no release wrote a `code_fetched` row, so none was written
-- before this column anywhere a release runs.
--
-- MEASURED with store.BenchmarkUsageForDay (`-benchtime 5x -count 1`, two
-- cores of an Intel Core Ultra 7 265U, beside another session's builds): a
-- busy day of every other usage type derived in 77 ms, and the same day beside
-- fifty thousand records of reads, summing each one's count, in 193 ms — 116
-- ms the records, under the 150 ms a derived day may add (1 % of the
-- publisher's fifteen-second tick). That is what a record costs whatever it
-- counts, so a day of many more reads coalesced into as many records costs
-- the same, and fifty thousand reads with no reader reading twice in one
-- flush are the most that many reads can cost.
ALTER TABLE crewlet_events ADD COLUMN read_reads INTEGER NOT NULL DEFAULT 0;
