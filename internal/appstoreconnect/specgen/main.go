// Command specgen reads Apple's App Store Connect OpenAPI document (the
// openapi.oas.json in Apple's published zip) against this build:
//
//	go run ./internal/appstoreconnect/specgen -spec openapi.oas.json check
//	go run ./internal/appstoreconnect/specgen -spec openapi.oas.json topology > internal/appstoreconnect/topology_gen.go
//
// check lists the operations the document adds to the operation table, which
// each need a class, and those it no longer has; topology prints the related
// lists that place a resource in its app.
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"

	"github.com/crewlet/crewlet/internal/appstoreconnect"
)

func main() {
	path := flag.String("spec", "", "Apple's openapi.oas.json")
	flag.Parse()
	if *path == "" || flag.NArg() != 1 {
		fmt.Fprintln(os.Stderr, "usage: specgen -spec openapi.oas.json check|topology")
		os.Exit(2)
	}
	if err := run(*path, flag.Arg(0)); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(path, mode string) error {
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer func() { _ = f.Close() }()
	s, err := readSpec(f)
	if err != nil {
		return err
	}
	switch mode {
	case "check":
		return check(s)
	case "topology":
		src, err := format.Source([]byte(topology(s)))
		if err != nil {
			return fmt.Errorf("specgen: format the topology: %w", err)
		}
		_, err = os.Stdout.Write(src)
		return err
	}
	return fmt.Errorf("specgen: %q is neither check nor topology", mode)
}

func check(s *spec) error {
	ops, err := s.operations()
	if err != nil {
		return err
	}
	have := map[string]bool{}
	for _, op := range appstoreconnect.Catalog().Operations {
		have[op.Method+" "+op.Path] = true
	}
	seen := map[string]bool{}
	var added []string
	for _, op := range ops {
		k := op.Method + " " + op.Path
		seen[k] = true
		if !have[k] {
			added = append(added, k+" ("+op.ID+")")
		}
	}
	var gone []string
	for k := range have {
		if !seen[k] {
			gone = append(gone, k)
		}
	}
	sort.Strings(gone)
	fmt.Printf("document %s: %d operations; %d new, %d no longer listed\n", s.Info.Version, len(ops), len(added), len(gone))
	for _, a := range added {
		fmt.Println("new:", a)
	}
	for _, g := range gone {
		fmt.Println("gone:", g)
	}
	if len(added)+len(gone) > 0 {
		return fmt.Errorf("specgen: the operation table does not match the document")
	}
	return nil
}

func topology(s *spec) string {
	down := s.downward()
	types := make([]string, 0, len(down))
	for t := range down {
		if t != "apps" {
			types = append(types, t)
		}
	}
	sort.Strings(types)
	var b strings.Builder
	b.WriteString("// Generated by specgen topology from App Store Connect API " + s.Info.Version + "; DO NOT EDIT.\n\n")
	b.WriteString("package appstoreconnect\n\n")
	b.WriteString("// downward is, per resource type an app owns, the related lists from an app down to it.\n")
	b.WriteString("var downward = map[string][]string{\n")
	for _, t := range types {
		quoted := make([]string, len(down[t]))
		for i, p := range down[t] {
			quoted[i] = fmt.Sprintf("%q", p)
		}
		fmt.Fprintf(&b, "\t%q: {%s},\n", t, strings.Join(quoted, ", "))
	}
	b.WriteString("}\n")
	return b.String()
}
