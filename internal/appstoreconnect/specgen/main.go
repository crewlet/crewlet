// Command specgen reads Apple's App Store Connect OpenAPI document (the
// openapi.oas.json in Apple's published zip) against this build:
//
//	go run ./internal/appstoreconnect/specgen -spec openapi.oas.json check
//	go run ./internal/appstoreconnect/specgen -spec openapi.oas.json topology > internal/appstoreconnect/topology_gen.go
//
// check lists the operations the document adds to the operation table, which
// each need a class, and those it no longer has; topology prints the resource
// types an app owns and the reads that place one in its app.
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"

	"github.com/crewlet/crewlet/internal/appstoreconnect"
)

func main() {
	path := flag.String("spec", "", "Apple's openapi.oas.json")
	flag.Parse()
	if *path == "" || flag.NArg() != 1 {
		fmt.Fprintln(os.Stderr, "usage: specgen -spec openapi.oas.json check|topology")
		os.Exit(2)
	}
	if err := run(*path, flag.Arg(0)); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(path, mode string) error {
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer func() { _ = f.Close() }()
	s, err := readSpec(f)
	if err != nil {
		return err
	}
	switch mode {
	case "check":
		return check(s)
	case "topology":
		src, err := format.Source([]byte(topology(s)))
		if err != nil {
			return fmt.Errorf("specgen: format the topology: %w", err)
		}
		_, err = os.Stdout.Write(src)
		return err
	}
	return fmt.Errorf("specgen: %q is neither check nor topology", mode)
}

func check(s *spec) error {
	ops, err := s.operations()
	if err != nil {
		return err
	}
	have := map[string]bool{}
	for _, op := range appstoreconnect.Catalog().Operations {
		have[op.Method+" "+op.Path] = true
	}
	seen := map[string]bool{}
	var added []string
	for _, op := range ops {
		k := op.Method + " " + op.Path
		seen[k] = true
		if !have[k] {
			added = append(added, k+" ("+op.ID+")")
		}
	}
	var gone []string
	for k := range have {
		if !seen[k] {
			gone = append(gone, k)
		}
	}
	sort.Strings(gone)
	fmt.Printf("document %s: %d operations; %d new, %d no longer listed\n", s.Info.Version, len(ops), len(added), len(gone))
	for _, a := range added {
		fmt.Println("new:", a)
	}
	for _, g := range gone {
		fmt.Println("gone:", g)
	}
	if len(added)+len(gone) > 0 {
		return fmt.Errorf("specgen: the operation table does not match the document")
	}
	return nil
}

func topology(s *spec) string {
	owned := s.owned()
	ups := s.upward(owned)
	down := s.downward(owned, ups)
	filters := s.idFilters()
	var b strings.Builder
	b.WriteString("// Generated by specgen topology from App Store Connect API " + s.Info.Version + "; DO NOT EDIT.\n\n")
	b.WriteString("package appstoreconnect\n\nimport \"sync\"\n\n")
	b.WriteString("// topology is built at first use, so the package allocates nothing at init.\n")
	b.WriteString("var topology = sync.OnceValue(func() topologyTables {\n\treturn topologyTables{\n")
	b.WriteString("\t\t// owned is every resource type that belongs to exactly one app (package doc, \"Scope\").\n")
	b.WriteString("\t\towned: map[string]bool{\n")
	for _, t := range sortedKeys(owned) {
		fmt.Fprintf(&b, "\t\t\t%q: true,\n", t)
	}
	b.WriteString("\t\t},\n\t\t// upward is, per owned type, the instance read that includes the to-one relationships\n")
	b.WriteString("\t\t// leading to its app, nearest first.\n\t\tupward: map[string]upLink{\n")
	for _, t := range sortedKeys(ups) {
		fmt.Fprintf(&b, "\t\t\t%q: {path: %q, rels: %s},\n", t, ups[t].Path, quoted(ups[t].Rels))
	}
	b.WriteString("\t\t},\n\t\t// downward is, per owned type with no upward read, the related reads from an app down\n")
	b.WriteString("\t\t// to it through owned types alone.\n\t\tdownward: map[string][]hop{\n")
	for _, t := range sortedKeys(down) {
		hops := make([]string, len(down[t]))
		for i, h := range down[t] {
			hops[i] = fmt.Sprintf("{path: %q, one: %t}", h.Path, h.One)
		}
		fmt.Fprintf(&b, "\t\t\t%q: {%s},\n", t, strings.Join(hops, ", "))
	}
	b.WriteString("\t\t},\n\t\t// idFilters is, per list read, the filters that name resources by ID, and their type.\n")
	b.WriteString("\t\tidFilters: map[string]map[string]string{\n")
	for _, p := range sortedKeys(filters) {
		var kv []string
		for _, f := range sortedKeys(filters[p]) {
			kv = append(kv, fmt.Sprintf("%q: %q", f, filters[p][f]))
		}
		fmt.Fprintf(&b, "\t\t\t%q: {%s},\n", p, strings.Join(kv, ", "))
	}
	b.WriteString("\t\t},\n\t}\n})\n")
	return b.String()
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func quoted(ss []string) string {
	q := make([]string, len(ss))
	for i, s := range ss {
		q[i] = fmt.Sprintf("%q", s)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}
